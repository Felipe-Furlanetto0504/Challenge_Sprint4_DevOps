-- 1.1 Registro das excecoes tratadas pelos pacotes (independente do dominio)
CREATE TABLE TB_LOG_ERRO (
    ID_LOG          NUMBER GENERATED ALWAYS AS IDENTITY,
    NOME_PROCEDURE  VARCHAR2(100)  NOT NULL,
    NOME_USUARIO    VARCHAR2(50)   DEFAULT USER    NOT NULL,
    DATA_ERRO       DATE           DEFAULT SYSDATE NOT NULL,
    CODIGO_ERRO     NUMBER         NOT NULL,
    MENSAGEM_ERRO   VARCHAR2(500)  NOT NULL,
    PARAMETROS      VARCHAR2(1000),
    CONSTRAINT PK_LOG_ERRO PRIMARY KEY (ID_LOG)
);

-- 1.2 Trilha de auditoria alimentada pelos gatilhos (independente do dominio)
CREATE TABLE TB_AUDITORIA (
    ID_AUDITORIA    NUMBER GENERATED ALWAYS AS IDENTITY,
    NOME_TABELA     VARCHAR2(30)   NOT NULL,
    ID_REGISTRO     NUMBER(10),
    TIPO_OPERACAO   VARCHAR2(10)   NOT NULL,
    NOME_USUARIO    VARCHAR2(50)   DEFAULT USER NOT NULL,
    DATA_HORA       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    VALORES_OLD     VARCHAR2(4000),
    VALORES_NEW     VARCHAR2(4000),
    CONSTRAINT PK_AUDITORIA PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT CK_AUDITORIA_OPERACAO CHECK (TIPO_OPERACAO IN ('INSERT', 'UPDATE', 'DELETE'))
);

-- 1.3 Usuario: tutor do animal ou clinica (perfil ADMIN)
CREATE TABLE TB_USUARIO (
    ID_USUARIO      NUMBER(10),
    NOME            VARCHAR2(50)   NOT NULL,
    EMAIL           VARCHAR2(50)   NOT NULL,
    SENHA           VARCHAR2(255)  NOT NULL,
    CPF             NUMBER(11)     NOT NULL,
    TELEFONE        NUMBER(11),
    ROLE            VARCHAR2(10)   DEFAULT 'TUTOR'  NOT NULL,
    DATA_CADASTRO   DATE           DEFAULT SYSDATE  NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_USUARIO_CPF UNIQUE (CPF),
    CONSTRAINT CK_USUARIO_ROLE CHECK (ROLE IN ('ADMIN', 'TUTOR')),
    CONSTRAINT CK_USUARIO_EMAIL CHECK (INSTR(EMAIL, '@') > 1),
    CONSTRAINT CK_USUARIO_CPF CHECK (CPF BETWEEN 1 AND 99999999999),
    CONSTRAINT CK_USUARIO_TELEFONE CHECK (TELEFONE IS NULL OR TELEFONE BETWEEN 1000000000 AND 99999999999)
);

-- 1.4 Animal (pet): pertence a exatamente um usuario
CREATE TABLE TB_ANIMAL (
    ID_ANIMAL       NUMBER(10),
    ID_USUARIO      NUMBER(10)     NOT NULL,
    NOME_ANIMAL     VARCHAR2(30)   NOT NULL,
    ESPEC_ANIMAL    VARCHAR2(10)   NOT NULL,
    RACA_ANIMAL     VARCHAR2(35),
    IDADE_ANIMAL    VARCHAR2(30),
    PORTE_ANIMAL    VARCHAR2(10),
    PESO_ANIMAL     NUMBER(5,2),
    CONSTRAINT PK_ANIMAL PRIMARY KEY (ID_ANIMAL),
    CONSTRAINT FK_ANIMAL_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_USUARIO (ID_USUARIO),
    CONSTRAINT CK_ANIMAL_ESPECIE CHECK (ESPEC_ANIMAL IN ('CAO', 'GATO', 'COELHO', 'OUTRO')),
    CONSTRAINT CK_ANIMAL_PORTE CHECK (PORTE_ANIMAL IN ('PEQUENO', 'MEDIO', 'GRANDE')),
    CONSTRAINT CK_ANIMAL_PESO CHECK (PESO_ANIMAL > 0)
);

-- 1.5 Vacina: historico vacinal; ID_DOSE_ORIGEM liga o reforco a dose anterior
CREATE TABLE TB_VACINA (
    ID_VACINA       NUMBER(10),
    ID_ANIMAL       NUMBER(10)     NOT NULL,
    NOME_VACINA     VARCHAR2(30)   NOT NULL,
    DATA_VACINA     DATE           NOT NULL,
    PROX_DOSE       DATE,
    LOC_VACINACAO   VARCHAR2(100),
    ID_DOSE_ORIGEM  NUMBER(10),
    CONSTRAINT PK_VACINA PRIMARY KEY (ID_VACINA),
    CONSTRAINT FK_VACINA_ANIMAL FOREIGN KEY (ID_ANIMAL) REFERENCES TB_ANIMAL (ID_ANIMAL),
    CONSTRAINT FK_VACINA_DOSE_ORIGEM FOREIGN KEY (ID_DOSE_ORIGEM) REFERENCES TB_VACINA (ID_VACINA),
    CONSTRAINT UK_VACINA_DOSE_ORIGEM UNIQUE (ID_DOSE_ORIGEM),
    CONSTRAINT CK_VACINA_PROX_DOSE CHECK (PROX_DOSE IS NULL OR PROX_DOSE > DATA_VACINA)
);

-- 1.6 Consulta: agenda e historico clinico do animal
CREATE TABLE TB_CONSULTA (
    ID_CONSULTA     NUMBER(10),
    ID_ANIMAL       NUMBER(10)     NOT NULL,
    TIPO_CONSULTA   VARCHAR2(30)   NOT NULL,
    DATA_CONSULTA   DATE           NOT NULL,
    HORA_CONSULTA   VARCHAR2(5),
    LOCAL_CONSULTA  VARCHAR2(100),
    STATUS          VARCHAR2(15)   DEFAULT 'INDEFINIDA' NOT NULL,
    OBSERVACAO      VARCHAR2(255),
    CONSTRAINT PK_CONSULTA PRIMARY KEY (ID_CONSULTA),
    CONSTRAINT FK_CONSULTA_ANIMAL FOREIGN KEY (ID_ANIMAL) REFERENCES TB_ANIMAL (ID_ANIMAL),
    CONSTRAINT CK_CONSULTA_STATUS CHECK (STATUS IN ('INDEFINIDA', 'AGENDADA', 'CONFIRMADA', 'REALIZADA', 'CANCELADA')),
    CONSTRAINT CK_CONSULTA_HORA CHECK (HORA_CONSULTA IS NULL OR REGEXP_LIKE(HORA_CONSULTA, '^([01][0-9]|2[0-3]):[0-5][0-9]$'))
);

-- 1.7 Notificacao: avisos para o tutor (ID_USUARIO preenchido) ou para a clinica (nulo)
CREATE TABLE TB_FV_NOTIFICACAO (
    ID_NOTIFICACAO  NUMBER(10),
    ID_USUARIO      NUMBER(10),
    TIPO            VARCHAR2(30)   NOT NULL,
    NOME_ANIMAL     VARCHAR2(30),
    DETALHE         VARCHAR2(100),
    DATA_EVENTO     DATE,
    CRIADA_EM       TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    LIDA            NUMBER(1)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FV_NOTIFICACAO PRIMARY KEY (ID_NOTIFICACAO),
    CONSTRAINT FK_FV_NOTIF_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TB_USUARIO (ID_USUARIO),
    CONSTRAINT CK_FV_NOTIF_LIDA CHECK (LIDA IN (0, 1)),
    CONSTRAINT CK_FV_NOTIF_TIPO CHECK (TIPO IN ('CONSULTA_SOLICITADA', 'CONSULTA_REAGENDADA',
        'CONSULTA_CONFIRMADA', 'CONSULTA_CANCELADA', 'CONSULTA_REALIZADA', 'VACINA_REGISTRADA',
        'REFORCO_REGISTRADO'))
);

-- 1.8 Tabela tecnica de controle de concorrencia da agenda (usada pelo backend Java)
CREATE TABLE TB_FV_AGENDA_LOCK (
    ID              NUMBER(1),
    CONSTRAINT PK_FV_AGENDA_LOCK PRIMARY KEY (ID),
    CONSTRAINT CK_FV_AGENDA_LOCK CHECK (ID = 1)
);

/* ---------------------------------------------------------------------
   2. INDICES
   --------------------------------------------------------------------- */
CREATE UNIQUE INDEX UX_USUARIO_EMAIL_LOWER ON TB_USUARIO (LOWER(EMAIL));
CREATE INDEX IX_ANIMAL_USUARIO ON TB_ANIMAL (ID_USUARIO);
CREATE INDEX IX_VACINA_ANIMAL ON TB_VACINA (ID_ANIMAL);
CREATE INDEX IX_VACINA_PROX_DOSE ON TB_VACINA (PROX_DOSE);
CREATE INDEX IX_CONSULTA_ANIMAL ON TB_CONSULTA (ID_ANIMAL);
CREATE INDEX IX_CONSULTA_AGENDA ON TB_CONSULTA (DATA_CONSULTA, HORA_CONSULTA);
CREATE INDEX IX_FV_NOTIF_DESTINO ON TB_FV_NOTIFICACAO (ID_USUARIO, LIDA);
CREATE INDEX IX_AUDITORIA_TABELA ON TB_AUDITORIA (NOME_TABELA, ID_REGISTRO);

